"""Session-local V2 command correlation. No domain state or reconnect authority."""

from __future__ import annotations

import asyncio
from collections.abc import Callable
from dataclasses import dataclass, field
from enum import StrEnum

from .protocol_v2 import AckResult, Command, CommandAck, CommandType, encode_client_message


class CommandFailure(RuntimeError):
    """Bounded local failure; an uncertain command may already have taken effect."""


class TransportLost(CommandFailure):
    pass


class CommandTimeout(CommandFailure):
    pass


class CommandCapacity(CommandFailure):
    pass


class AckAdvice(StrEnum):
    COMPLETE = "complete"
    SERVER_STATE = "server_state"
    PHASE = "phase"
    CLOSING = "closing_input"
    SNAPSHOT = "snapshot_required"
    CLIENT_ERROR = "client_error"
    TRIGGER_UNAVAILABLE = "trigger_unavailable"
    AUDIO_UNAVAILABLE = "audio_unavailable"
    SETTINGS_CONFLICT = "settings_revision_conflict"
    SETTINGS_ERRORS = "settings_errors"


ADVICE = {
    AckResult.APPLIED: AckAdvice.COMPLETE,
    AckResult.NO_CHANGE: AckAdvice.COMPLETE,
    AckResult.ACTIVATION_LOCKED: AckAdvice.SERVER_STATE,
    AckResult.NOT_ACTIVE: AckAdvice.SERVER_STATE,
    AckResult.INVALID_PHASE: AckAdvice.PHASE,
    AckResult.CLOSING_INPUT: AckAdvice.CLOSING,
    AckResult.STALE_SESSION: AckAdvice.CLIENT_ERROR,
    AckResult.STALE_ACTIVATION: AckAdvice.SNAPSHOT,
    AckResult.COMMAND_ID_CONFLICT: AckAdvice.CLIENT_ERROR,
    AckResult.INVALID_PAYLOAD: AckAdvice.CLIENT_ERROR,
    AckResult.TRIGGER_SUPPRESSED: AckAdvice.TRIGGER_UNAVAILABLE,
    AckResult.AUDIO_UNAVAILABLE: AckAdvice.AUDIO_UNAVAILABLE,
    AckResult.SETTINGS_REVISION_CONFLICT: AckAdvice.SETTINGS_CONFLICT,
    AckResult.SETTINGS_REJECTED: AckAdvice.SETTINGS_ERRORS,
    AckResult.INTERNAL_ERROR: AckAdvice.SNAPSHOT,
}


@dataclass(frozen=True)
class CommandCompletion:
    command: Command
    ack: CommandAck
    generation: int
    projectable: bool
    advice: AckAdvice


@dataclass
class PendingCommand:
    command: Command
    generation: int
    wire: str = field(repr=False)
    future: asyncio.Future = field(repr=False)


class CommandTracker:
    """One instance per admitted socket. IDs/payloads never migrate or repeat.

    Same-domain requests serialize before sending; at most max_pending callers
    (including domain waiters) are accepted. Timeout permits only a byte-identical
    retry; the transport must recycle an uncertain socket before new mutations.
    """

    def __init__(self, session_id: str, generation: int, *, ack_timeout: float = 5,
                 retries: int = 1, max_pending: int = 16,
                 on_completion: Callable[[CommandCompletion], None] | None = None):
        if ack_timeout <= 0 or retries not in (0, 1) or max_pending < 1:
            raise ValueError("invalid command bounds")
        self.session_id, self.generation = session_id, generation
        self.ack_timeout, self.retries, self.max_pending = ack_timeout, retries, max_pending
        self.on_completion = on_completion
        self.pending: dict[str, PendingCommand] = {}
        self._locks = {kind: asyncio.Lock() for kind in CommandType}
        self._callers = 0
        self._closed = False
        self.state_version = 0
        self.settings_revision = 0

    def observe(self, state_version: int, settings_revision: int | None = None):
        self.state_version = max(self.state_version, state_version)
        if settings_revision is not None:
            self.settings_revision = max(self.settings_revision, settings_revision)

    async def request(self, command: Command, send) -> CommandCompletion:
        if self._closed or command.sessionId != self.session_id:
            raise TransportLost("command session is no longer current")
        if self._callers >= self.max_pending:
            raise CommandCapacity("command capacity reached")
        self._callers += 1
        try:
            async with self._locks[CommandType(command.type)]:
                if self._closed:
                    raise TransportLost("command session is no longer current")
                # IDs are generated by the transport once per logical request.
                if command.commandId in self.pending:
                    raise CommandFailure("command ID already pending")
                future = asyncio.get_running_loop().create_future()
                pending = PendingCommand(command, self.generation, encode_client_message(command), future)
                self.pending[command.commandId] = pending
                try:
                    for attempt in range(self.retries + 1):
                        if self._closed:
                            raise TransportLost("transport_lost")
                        await asyncio.wait_for(send(pending.wire), self.ack_timeout)
                        try:
                            return await asyncio.wait_for(asyncio.shield(future), self.ack_timeout)
                        except TimeoutError:
                            if attempt == self.retries:
                                # No later mutation may pass this domain lock on
                                # an uncertain session, even before caller cleanup.
                                self.close()
                                raise CommandTimeout("command outcome unknown") from None
                    raise AssertionError("unreachable")
                finally:
                    self.pending.pop(command.commandId, None)
                    if not future.done():
                        future.cancel()
                    elif not future.cancelled():
                        future.exception()  # consume loss if send/caller was cancelled
        finally:
            self._callers -= 1

    def resolve(self, ack: CommandAck, generation: int) -> bool:
        if self._closed or generation != self.generation or ack.sessionId != self.session_id:
            return False
        pending = self.pending.get(ack.commandId)
        if pending is None or pending.future.done():
            return False
        projectable = ack.stateVersion >= self.state_version and ack.settingsRevision >= self.settings_revision
        completion = CommandCompletion(pending.command, ack, generation, projectable, ADVICE[ack.result])
        self.observe(ack.stateVersion, ack.settingsRevision)
        # Synchronous delivery preserves receive order. Callbacks must not block
        # or issue awaited requests on the receive task.
        if self.on_completion:
            self.on_completion(completion)
        pending.future.set_result(completion)
        return True

    def close(self):
        self._closed = True
        for pending in tuple(self.pending.values()):
            if not pending.future.done():
                pending.future.set_exception(TransportLost("transport_lost"))

    @property
    def pending_count(self) -> int:
        return sum(not item.future.done() for item in self.pending.values())
